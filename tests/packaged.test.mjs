import test from "node:test";
import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import path from "node:path";
import { _electron } from "playwright-core";
import { createRunDirectory } from "../dist/validation/run-directory.js";
import { stopAndCloseDesktop } from "./desktop-helpers.mjs";

test("packaged application uses bundled runtimes with a fresh profile and no developer PATH", { timeout: 180000 }, async () => {
  const run = createRunDirectory("packaged 中文"), project = path.join(run.root, "catalog project");
  const executable = realpathSync(process.env.LCODEX_PACKAGE_EXECUTABLE ?? ".local/releases/win-unpacked/lcodex.exe");
  assert.ok(executable.toLowerCase().startsWith(path.resolve(".local").toLowerCase() + path.sep));
  const node = path.join(path.dirname(executable), "resources/runtimes/node/node.exe");
  const command = "npm.cmd test; exit $LASTEXITCODE";
  const source = "export function total(items) { return items.reduce((sum, item) => sum + item.unitCents, 0); }\n";
  for (const directory of [project, path.join(project, "test"), ...["temp", "profile/roaming", "profile/local"].map(name => path.join(run.root, name))]) mkdirSync(directory, { recursive: true });
  writeFileSync(path.join(project, "package.json"), JSON.stringify({ name: "packaged-fixture", private: true, type: "module", scripts: { test: "node --test" } }));
  writeFileSync(path.join(project, "catalog.mjs"), source);
  writeFileSync(path.join(project, "test/catalog.test.mjs"), "import test from 'node:test'; import assert from 'node:assert/strict'; import {total} from '../catalog.mjs'; console.log('NODE_LOCATION',process.execPath); test('quantity',()=>assert.equal(total([{unitCents:25,quantity:4}]),100));\n");
  const acceptor = path.join(run.root, "independent.mjs");
  writeFileSync(acceptor, "import assert from 'node:assert/strict';import {pathToFileURL} from 'node:url';const {total}=await import(pathToFileURL(process.argv[2]));assert.equal(total([]),0);assert.equal(total([{unitCents:25,quantity:4}]),100);assert.equal(total([{unitCents:8,quantity:0},{unitCents:9,quantity:3}]),27);console.log('3/3 independent checks');");
  const acceptanceBefore = readFileSync(acceptor), originalBudget = readFileSync(".local/state/p1-budget.jsonl", "utf8");
  assert.notEqual(spawnSync(node, [acceptor, path.join(project, "catalog.mjs")]).status, 0, "Initial independent baseline must reproduce the defect");
  const env = Object.fromEntries(Object.entries(process.env).filter(([key]) => ["SYSTEMROOT", "WINDIR", "COMSPEC", "PATHEXT", "USERPROFILE", "APPDATA", "LOCALAPPDATA"].includes(key.toUpperCase())));
  Object.assign(env, { PATH: path.join(process.env.SystemRoot, "System32"), TEMP: path.join(run.root, "temp"), TMP: path.join(run.root, "temp") });
  const args = ["--user-data-dir=" + path.join(run.root, "profile/roaming")];
  let app, clean = false;
  try {
    app = await _electron.launch({ executablePath: executable, args, cwd: run.root, env, timeout: 40000 });
    let page = await app.firstWindow(); await page.getByRole("heading", { name: "从一个本地项目开始" }).waitFor();
    const info = await app.evaluate(({ app }) => ({ packaged: app.isPackaged, data: app.getPath("userData") }));
    assert.equal(info.packaged, true); assert.ok(path.relative(run.root, info.data).startsWith("profile"));
    const initial = await page.evaluate(() => window.lcodex.request({ type: "snapshot" }));
    assert.equal(initial.state.version, JSON.parse(readFileSync("package.json", "utf8")).version);
    assert.deepEqual([initial.state.runtime.engine, initial.state.runtime.shell, initial.state.runtime.node], [true, true, true]);
    assert.equal(initial.state.budget.scope, "personal"); assert.equal(initial.state.budget.configured, false); assert.equal(initial.state.pricing.current, false);
    await app.evaluate((_electron, command) => { globalThis.lcodexTestCommand = command; globalThis.lcodexTestReadBeforeChecks = true; }, command);
    await app.evaluate((_electron, script) => { (0, eval)(script); }, readFileSync("tests/mock-model.mjs", "utf8"));
    await page.getByRole("button", { name: "设置", exact: true }).click();
    await page.getByLabel("DeepSeek API Key", { exact: true }).fill("sk-synthetic-packaged-not-a-real-key");
    await page.getByRole("button", { name: "保存密钥", exact: true }).click();
    await page.getByText("密钥已加密保存", { exact: true }).waitFor();
    await page.getByLabel("累计预算上限（元）", { exact: true }).fill("2");
    await page.getByLabel("单任务上限（元）", { exact: true }).fill("0.5");
    await page.getByRole("button", { name: "确认并启用预算", exact: true }).click();
    await page.getByRole("button", { name: "已核对今日价格与上述记录一致", exact: true }).click();
    await page.getByRole("button", { name: "关闭设置", exact: true }).click();
    await page.getByText("单任务最多 ¥0.5", { exact: true }).waitFor();
    for (const directory of [info.data, path.dirname(info.data)]) {
      await app.evaluate(({ dialog }, directory) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [directory] }); }, directory);
      const rejected = await page.evaluate(() => window.lcodex.request({ type: "choose-project" }));
      assert.equal(rejected.ok, false); assert.equal(rejected.code, "PROJECT_OVERLAPS_APP_DATA");
    }
    await app.evaluate(({ dialog }, directory) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [directory] }); }, project);
    await page.getByRole("button", { name: "选择项目", exact: true }).click();
    await page.getByRole("heading", { name: "一起构建 catalog project" }).waitFor();
    let snapshot = await page.evaluate(() => window.lcodex.request({ type: "snapshot" }));
    const chatId = snapshot.state.activeChatId, projectId = snapshot.state.chats.find(chat => chat.id === chatId).projectId;
    await page.evaluate(({projectId, command}) => window.lcodex.request({ type: "set-test-command", projectId, command }), {projectId, command});
    await page.getByRole("combobox", { name: "任务方式" }).selectOption("write");
    await page.getByRole("textbox", { name: "输入任务" }).fill("修复数量计算，运行 npm 测试（模拟模型，实际发布程序）。");
    await page.getByRole("button", { name: "发送任务", exact: true }).click();
    const deadline = Date.now() + 100000;
    let chat;
    do {
      snapshot = await page.evaluate(() => window.lcodex.request({ type: "snapshot" }));
      chat = snapshot.state.chats.find(chat => chat.id === chatId);
      if (["ended", "failed", "stopped", "reconcile"].includes(chat.execution)) break;
      await new Promise(resolve => setTimeout(resolve, 100));
    } while (Date.now() < deadline);
    assert.equal(chat.execution, "ended", JSON.stringify({ error: chat.error, tools: chat.tools }));
    assert.equal(chat.verification, "passed"); assert.equal(chat.baselineExit, 1);
    assert.ok(chat.tools.some(tool => tool.output.includes("resources\\runtimes\\node\\node.exe")), "Commands must use bundled Node, not a developer installation");
    assert.equal(readFileSync(path.join(project, "catalog.mjs"), "utf8"), source, "Original stays untouched before review");
    const manifest = JSON.parse(readFileSync(path.join(info.data, "tasks", chatId, "task.json"), "utf8"));
    assert.match(execFileSync(node, [acceptor, path.join(manifest.taskDirectory, "workspace/catalog.mjs")], { encoding: "utf8" }), /3\/3/);
    await page.getByRole("button", { name: /^改动/ }).click();
    await page.getByRole("button", { name: "应用全部", exact: true }).click();
    await page.getByText("已应用", { exact: true }).waitFor();
    assert.match(execFileSync(node, [acceptor, path.join(project, "catalog.mjs")], { encoding: "utf8" }), /3\/3/);
    assert.deepEqual(readFileSync(acceptor), acceptanceBefore);
    await app.close(); app = await _electron.launch({ executablePath: executable, args, cwd: run.root, env, timeout: 40000 }); page = await app.firstWindow();
    await page.getByRole("textbox", { name: "输入任务" }).waitFor();
    const resumed = await page.evaluate(() => window.lcodex.request({ type: "snapshot" }));
    assert.equal(resumed.state.budget.limit, 2); assert.equal(resumed.state.budget.perTask, 0.5); assert.equal(resumed.state.runtime.key, true);
    assert.equal(readFileSync(".local/state/p1-budget.jsonl", "utf8"), originalBudget);
    mkdirSync(".local/reports", { recursive: true });
    await page.screenshot({ path: ".local/reports/packaged-review.png" });
    clean = true;
  } finally { await stopAndCloseDesktop(app); if (clean) run.cleanup(); else console.log("Retained packaged fixture:", path.basename(run.root)); }
});
