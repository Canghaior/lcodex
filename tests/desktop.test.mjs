import test from "node:test";
import assert from "node:assert/strict";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { _electron } from "playwright-core";
import electronPath from "electron";
import { createRunDirectory } from "../dist/validation/run-directory.js";

test("Electron project selection, protected preview, layout, IPC isolation and persisted navigation", { timeout: 120_000 }, async () => {
  const run = createRunDirectory("desktop 中文项目"), fixture = path.join(run.root, "sample project");
  mkdirSync(fixture);
  writeFileSync(path.join(fixture, "README.md"), "# Catalog Studio\n\nA small local project.\n\n- Understand code\n- Review changes\n\n<script>window.injected=true</script>\n\n![remote](https://example.com/leak.png)\n");
  writeFileSync(path.join(fixture, "catalog.mjs"), "export const total = items => items.reduce((sum, item) => sum + item.price, 0);\n");
  writeFileSync(path.join(fixture, ".env"), "PRIVATE_TOKEN=synthetic-fixture-only\n");
  const before = readFileSync(path.join(fixture, "catalog.mjs"), "utf8");
  const env = Object.fromEntries(Object.entries(process.env).filter(([key]) => ["PATH", "SYSTEMROOT", "WINDIR", "COMSPEC", "PATHEXT", "USERPROFILE", "APPDATA", "LOCALAPPDATA"].includes(key.toUpperCase())));
  mkdirSync(path.join(run.root, "temp"));
  Object.assign(env, { LCODEX_DESKTOP_TEST_ROOT: run.root, TEMP: path.join(run.root, "temp"), TMP: path.join(run.root, "temp") });
  let application, ended = false;
  const errors = [];
  try {
    application = await _electron.launch({ executablePath: electronPath, args: ["."], cwd: path.resolve("."), env, timeout: 30_000 });
    const page = await application.firstWindow();
    page.on("pageerror", error => errors.push(error.message));
    await page.getByRole("heading", { name: "从一个本地项目开始" }).waitFor();
    assert.deepEqual(await page.evaluate(() => ({ require: typeof window.require, process: typeof window.process, bridge: Object.keys(window.lcodex).sort() })), { require: "undefined", process: "undefined", bridge: ["request", "subscribe"] });
    assert.equal((await page.evaluate(() => window.lcodex.request({ type: "execute", command: "anything" }))).code, "IPC_REFUSED");
    await application.evaluate(({ dialog }, fixture) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [fixture] }); }, fixture);
    await page.getByRole("button", { name: "选择项目", exact: true }).click();
    await page.getByRole("heading", { name: "一起构建 sample project" }).waitFor({ timeout: 30_000 });
    await page.getByRole("button", { name: "README.md", exact: true }).click();
    await page.getByRole("heading", { name: "Catalog Studio" }).waitFor();
    assert.equal(await page.locator(".file-content img").count(), 0);
    assert.equal(await page.evaluate(() => window.injected), undefined);
    const reply = await page.evaluate(() => window.lcodex.request({ type: "snapshot" }));
    assert.equal(reply.ok, true);
    assert.equal(reply.state.projects[0].excluded, 1);
    assert.equal(reply.state.runtime.shell, true);
    const refused = await page.evaluate(projectId => window.lcodex.request({ type: "open-file", projectId, relative: "../.env" }), reply.state.projects[0].id);
    assert.equal(refused.ok, false);
    await page.getByRole("button", { name: "查看源文本", exact: true }).click();
    assert.match(await page.locator(".source-view").textContent(), /# Catalog Studio/);
    await page.getByRole("button", { name: "查看预览", exact: true }).click();
    await page.getByRole("textbox", { name: "输入任务" }).fill("解释这个项目的结构，先不要修改文件。");
    await page.getByRole("combobox", { name: "任务方式" }).selectOption("write");
    const firstChatId = reply.state.activeChatId;
    await page.getByRole("button", { name: "在 sample project 中新建聊天" }).click();
    await page.getByRole("textbox", { name: "输入任务" }).fill("另一个问题");
    await page.locator(".chat-row").first().click();
    assert.equal(await page.getByRole("textbox", { name: "输入任务" }).inputValue(), "解释这个项目的结构，先不要修改文件。");
    assert.equal(await page.getByRole("combobox", { name: "任务方式" }).inputValue(), "write");
    assert.equal(reply.state.runtime.key, false);
    const beforeWidth = (await page.locator(".chat-panel").boundingBox()).width;
    await page.getByRole("separator").focus(); await page.keyboard.press("ArrowRight");
    assert.ok((await page.locator(".chat-panel").boundingBox()).width > beforeWidth);
    await page.getByRole("textbox", { name: "输入任务" }).focus();
    mkdirSync(path.resolve(".local/reports"), { recursive: true });
    await page.screenshot({ path: path.resolve(".local/reports/desktop-wide.png") });
    await application.evaluate(({ BrowserWindow }) => { const win = BrowserWindow.getAllWindows()[0]; win.setSize(900, 760); win.webContents.setZoomFactor(1.25); });
    await page.waitForFunction(() => window.innerWidth < 800);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    const input = await page.getByRole("textbox", { name: "输入任务" }).boundingBox();
    assert.ok(input && input.y + input.height <= await page.evaluate(() => window.innerHeight));
    assert.ok(input.x + input.width <= await page.evaluate(() => window.innerWidth));
    const close = await page.getByRole("button", { name: "关闭窗口", exact: true }).boundingBox();
    assert.ok(close.x + close.width <= await page.evaluate(() => window.innerWidth));
    const nativeScreenshot = await application.evaluate(async ({ BrowserWindow }) => (await BrowserWindow.getAllWindows()[0].webContents.capturePage()).toPNG().toString("base64"));
    writeFileSync(path.resolve(".local/reports/desktop-narrow.png"), Buffer.from(nativeScreenshot, "base64"));
    assert.deepEqual(errors, []);
    await application.close(); application = undefined;
    application = await _electron.launch({ executablePath: electronPath, args: ["."], cwd: path.resolve("."), env });
    const reopened = await application.firstWindow();
    await reopened.getByRole("heading", { name: "一起构建 sample project" }).waitFor();
    const restored = await reopened.evaluate(() => window.lcodex.request({ type: "snapshot" }));
    assert.equal(restored.state.chats.length, 2);
    assert.equal(restored.state.activeChatId, firstChatId);
    assert.equal(readFileSync(path.join(fixture, "catalog.mjs"), "utf8"), before);
  } finally {
    if (application) await application.close();
    ended = true;
    if (ended) run.cleanup();
  }
});
